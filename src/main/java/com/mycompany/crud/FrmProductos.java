    private void limpiar() {

        txtId.setText("");
        txtNombre.setText("");
        txtPrecio.setText("");
        txtStock.setText("");

        if (cboCategoria.getItemCount() > 0) {
            cboCategoria.setSelectedIndex(0);
        }
        
        tblProductos.clearSelection();
    }
    private void actualizarProducto() {

        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this,"Seleccione un producto");
            return;
        }

        Double precio = obtenerPrecioValido();

        if (precio == null) {
            return;
        }

        Integer stock = obtenerStockValido();

        if (stock == null) {
            return;
        }
        
        try {

            int idProducto = Integer.parseInt(txtId.getText());

            String nombre = txtNombre.getText().trim();

            //double precio = Double.parseDouble(txtPrecio.getText());

            //int stock = Integer.parseInt( txtStock.getText());

            String categoria = cboCategoria.getSelectedItem().toString();

            int idCategoria = categorias.get(categoria);

            String sql =
                "UPDATE producto " +
                "SET nombre = ?, " +
                "id_categoria = ?, " +
                "precio = ?, " +
                "stock = ? " +
                "WHERE id_producto = ?";

            try (
                Connection cn = Conexion.conectar();

                PreparedStatement ps = cn.prepareStatement(sql)
            ) {

                ps.setString(1, nombre);
                ps.setInt(2, idCategoria);
                ps.setDouble(3, precio);
                ps.setInt(4, stock);
                ps.setInt(5, idProducto);

                ps.executeUpdate();

                JOptionPane.showMessageDialog( this, "Producto actualizado");

                limpiar();

                listarProductos();
                
                estadoInicial();
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,"Error: " + e.getMessage());
        }
    }
    
    private void eliminarProducto() {

        if (txtId.getText().isEmpty()) {

            JOptionPane.showMessageDialog(this,"Seleccione un producto");

            return;
        }

        int respuesta =
            JOptionPane.showConfirmDialog(this,"¿Desea eliminar el producto?", "Confirmar",JOptionPane.YES_NO_OPTION,JOptionPane.WARNING_MESSAGE);

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        String sql =
            "DELETE FROM producto " +
            "WHERE id_producto = ?";

        try (
            Connection cn = Conexion.conectar();

            PreparedStatement ps = cn.prepareStatement(sql)
        ) {

            int id = Integer.parseInt( txtId.getText());

            ps.setInt(1, id);

            ps.executeUpdate();

            JOptionPane.showMessageDialog(this,"Producto eliminado");

            limpiar();

            listarProductos();
            
            estadoInicial();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,"Error al eliminar: "+ e.getMessage());
        }
    }
    
    private boolean validarCampos() {

        if (txtNombre.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,"Ingrese el nombre del producto");

            txtNombre.requestFocus();

            return false;
        }

        if (cboCategoria.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(this,"Seleccione una categoría");

            return false;
        }

        if (txtPrecio.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,"Ingrese el precio");

            txtPrecio.requestFocus();

            return false;
        }

        if (txtStock.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this, "Ingrese el stock");

            txtStock.requestFocus();

            return false;
        }

        return true;
    }
    
    private Double obtenerPrecioValido() {

        try {

            double precio =
                Double.parseDouble(
                    txtPrecio.getText().trim()
                );

            if (precio <= 0) {

                JOptionPane.showMessageDialog(
                    this,
                    "El precio debe ser mayor que cero"
                );

                txtPrecio.requestFocus();
                return null;
            }

            return precio;

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "Ingrese un precio válido"
            );

            txtPrecio.requestFocus();
            return null;
        }
    }
    
    private Integer obtenerStockValido() {

        try {

            int stock =
                Integer.parseInt(
                    txtStock.getText().trim()
                );

            if (stock < 0) {

                JOptionPane.showMessageDialog(
                    this,
                    "El stock no puede ser negativo"
                );

                txtStock.requestFocus();
                return null;
            }

            return stock;

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "Ingrese un stock válido"
            );

            txtStock.requestFocus();
            return null;
        }
    }

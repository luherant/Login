    private void listarProductos() {

//        DefaultTableModel modelo =new DefaultTableModel();
//
//        modelo.addColumn("ID");
//        modelo.addColumn("Producto");
//        modelo.addColumn("Categoría");
//        modelo.addColumn("Precio");
//        modelo.addColumn("Stock");

    DefaultTableModel modelo = new DefaultTableModel( new Object[]{ "ID", "Producto", "Categoría", "Precio", "Stock"}, 0 ) { @Override public boolean isCellEditable(int row, int column) { return false; } };

        String sql =
            "SELECT p.id_producto, " +
            "       p.nombre, " +
            "       c.nombre AS categoria, " +
            "       p.precio, " +
            "       p.stock " +
            "FROM producto p " +
            "INNER JOIN categoria c " +
            "ON p.id_categoria = c.id_categoria " +
            "ORDER BY p.id_producto";

        try (
            Connection cn = Conexion.conectar();
            PreparedStatement ps = cn.prepareStatement(sql);
            ResultSet rs = ps.executeQuery()
        ) {

            while (rs.next()) {

                Object[] fila = {
                    rs.getInt("id_producto"),
                    rs.getString("nombre"),
                    rs.getString("categoria"),
                    rs.getDouble("precio"),
                    rs.getInt("stock")
                };

                modelo.addRow(fila);
            }

            tblProductos.setModel(modelo);

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,"Error al listar productos: "+ e.getMessage());
        }
    }
